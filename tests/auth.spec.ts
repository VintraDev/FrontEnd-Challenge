import { expect, test } from '@playwright/test'

test('login valida dados, retorna ao checkout, restaura sessão e encerra acesso', async ({ page }) => {
  await page.goto('/checkout')
  await expect(page).toHaveURL(/\/login\?redirect/)
  const dialog = page.getByRole('dialog')
  await expect(dialog).toBeVisible()
  await dialog.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(dialog.getByRole('alert')).toContainText('Informe um e-mail válido')
  await dialog.getByLabel('E-mail').fill('ana@kurio.test')
  await dialog.getByLabel('Senha', { exact: true }).fill('incorreta')
  await dialog.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(dialog.getByRole('alert')).toContainText('E-mail ou senha inválidos')
  await dialog.getByLabel('Senha', { exact: true }).fill('KurioDemo123!')
  await dialog.getByRole('button', { name: 'Mostrar senha' }).click()
  await expect(dialog.getByLabel('Senha', { exact: true })).toHaveAttribute('type', 'text')
  await dialog.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page).toHaveURL(/\/checkout$/)
  await expect(page.getByText('Ana Colecionadora')).toBeVisible()
  await page.reload()
  await expect(page.getByText('Ana Colecionadora')).toBeVisible()
  await page.getByRole('button', { name: 'Sair' }).click()
  await expect(page).toHaveURL(/\/login\?redirect/)
  await page.reload()
  await expect(page).toHaveURL(/\/login\?redirect/)
})

test('redirect externo é rejeitado e diálogo pode ser fechado pelo teclado', async ({ page }) => {
  await page.goto('/login?redirect=%2F%2Fevil.example')
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page).toHaveURL(/\/(?:\?.*)?$/)
  await page.goto('/login?redirect=%2F%2Fevil.example')
  await page.getByLabel('E-mail').fill('bruno@kurio.test')
  await page.getByLabel('Senha', { exact: true }).fill('KurioDemo456!')
  await page.getByRole('dialog').getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page).toHaveURL(/\/(?:\?.*)?$/)
  await expect(page.getByText('Bruno Colecionador')).toBeVisible()
})

test('sessão expirada retorna ao login sem perder o destino', async ({ page }) => {
  await page.goto('/login?redirect=%2Fcheckout')
  await page.getByLabel('E-mail').fill('ana@kurio.test')
  await page.getByLabel('Senha', { exact: true }).fill('KurioDemo123!')
  await page.getByRole('dialog').getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page).toHaveURL(/\/checkout$/)
  await page.evaluate(async () => {
    const token = localStorage.getItem('kurio-demo-session')!
    const db = await new Promise<IDBDatabase>((resolve, reject) => { const request = indexedDB.open('kurio-mock-auth', 3); request.onsuccess = () => resolve(request.result); request.onerror = () => reject(request.error) })
    await new Promise<void>((resolve, reject) => { const tx = db.transaction('sessions', 'readwrite'); const store = tx.objectStore('sessions'); const request = store.get(token); request.onsuccess = () => store.put({ ...request.result, expiresAt: 0 }, token); tx.oncomplete = () => resolve(); tx.onerror = () => reject(tx.error) })
    db.close()
  })
  await page.reload()
  await expect(page).toHaveURL(/\/login\?redirect/)
  await expect(page.getByRole('dialog')).toBeVisible()
})

