import { expect, test } from '@playwright/test'

test('busca no header consulta o catálogo, preserva filtros e reinicia paginação', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/')
  await expect(page.getByText('27 resultados')).toBeVisible()
  await page.getByRole('button', { name: '2', exact: true }).click()
  await expect(page).toHaveURL(/page=2/)
  const trigger = page.getByRole('button', { name: 'Abrir pesquisa' })
  await trigger.click()
  const search = page.getByRole('search', { name: '' })
  await search.getByLabel('Buscar NFTs').fill('Emerald')
  await search.getByRole('button', { name: 'Buscar', exact: true }).click()
  await expect(page).toHaveURL(/q=Emerald/)
  await expect(page.getByLabel('Buscar NFTs')).toHaveValue('Emerald')
  await expect(page.getByRole('button', { name: '1', exact: true })).toHaveAttribute('aria-current', 'page')
  await expect(page.getByText('3 resultados')).toBeVisible()
  await page.getByRole('checkbox', { name: 'Arte digital' }).check()
  await trigger.click()
  await search.getByLabel('Buscar NFTs').fill('inexistente')
  await search.getByRole('button', { name: 'Buscar', exact: true }).click()
  await expect(page.getByText('Nenhum NFT encontrado para estes filtros.')).toBeVisible()
  await expect(page.getByRole('checkbox', { name: 'Arte digital' })).toBeChecked()
  await page.reload()
  await expect(page.getByLabel('Buscar NFTs')).toHaveValue('inexistente')
  await expect(page.getByRole('checkbox', { name: 'Arte digital' })).toBeChecked()
})

test('busca pelo header funciona no detalhe e fecha com Escape', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/nft/nft-1')
  const trigger = page.getByRole('button', { name: 'Abrir pesquisa' })
  await trigger.focus()
  await page.keyboard.press('Enter')
  const search = page.getByRole('search')
  const input = search.getByLabel('Buscar NFTs')
  await expect(input).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(search).toBeHidden()
  await expect(trigger).toBeFocused()
  await trigger.click()
  await input.fill('Sage')
  await input.press('Enter')
  await expect(page).toHaveURL(/\/?\?.*q=Sage/)
  await expect(page.getByText('3 resultados')).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Sage Nomad #009', exact: true })).toBeVisible()
})
